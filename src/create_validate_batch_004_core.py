def validate(samples_to_check: list[dict]) -> None:
    errors = []
    expected_ids = {
        f"core_{number:03d}"
        for number in range(1, 31)
    }

    actual_ids = []
    prompts = []

    if len(samples_to_check) != 30:
        errors.append(
            f"تعداد نمونه‌ها باید ۳۰ باشد، اما {len(samples_to_check)} است."
        )

    for index, sample in enumerate(samples_to_check, start=1):
        messages = sample.get("messages")
        metadata = sample.get("metadata", {})
        sample_id = metadata.get("id")

        actual_ids.append(sample_id)

        if not isinstance(messages, list) or len(messages) != 3:
            errors.append(
                f"نمونه {index}: messages باید دقیقاً ۳ عضو داشته باشد."
            )
            continue

        roles = [
            message.get("role")
            for message in messages
        ]

        if roles != ["system", "user", "assistant"]:
            errors.append(
                f"نمونه {sample_id}: ترتیب نقش‌ها نادرست است."
            )

        for message in messages:
            content = message.get("content")

            if not isinstance(content, str) or not content.strip():
                errors.append(
                    f"نمونه {sample_id}: یک پیام خالی دارد."
                )

        if metadata.get("verified") is not True:
            errors.append(
                f"نمونه {sample_id}: verified باید True باشد."
            )

        if metadata.get("language") != "fa":
            errors.append(
                f"نمونه {sample_id}: language باید fa باشد."
            )

        source = metadata.get("source", {})

        if not source.get("book"):
            errors.append(
                f"نمونه {sample_id}: نام کتاب وجود ندارد."
            )

        pages = source.get("printed_pages")

        if (
            not isinstance(pages, list)
            or not pages
            or not all(
                isinstance(page, int) and page > 0
                for page in pages
            )
        ):
            errors.append(
                f"نمونه {sample_id}: شماره صفحات نامعتبر است."
            )

        prompts.append(messages[1]["content"])

    actual_id_set = set(actual_ids)

    if actual_id_set != expected_ids:
        errors.append(
            "شناسه‌های بچ با core_001 تا core_030 مطابقت ندارند."
        )

    if len(actual_ids) != len(actual_id_set):
        errors.append("شناسه تکراری وجود دارد.")

    if len(prompts) != len(set(prompts)):
        errors.append("سؤال تکراری وجود دارد.")

    joined_answers = " ".join(
        sample["messages"][2]["content"]
        for sample in samples_to_check
    )

    required_fragments = [
        "درشت‌مولکول",
        "واحد تکرارشونده",
        "پلیمریزاسیون زنجیره‌ای",
        "پلیمریزاسیون مرحله‌ای",
        "ترموپلاستیک",
        "ترموست",
        "Tg",
        "Tm",
        "Mn",
        "Mw",
        "Xn",
        "[η]",
        "Rp",
        "بینودال",
        "اسپینودال",
    ]

    for fragment in required_fragments:
        if fragment not in joined_answers:
            errors.append(
                f"عبارت علمی لازم در پاسخ‌ها وجود ندارد: {fragment}"
            )

    if errors:
        print("اعتبارسنجی ناموفق بود:")

        for error in errors:
            print("-", error)

        raise SystemExit(1)


def write_jsonl(samples_to_write: list[dict]) -> None:
    OUTPUT_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with OUTPUT_PATH.open(
        "w",
        encoding="utf-8",
    ) as file:
        for sample in samples_to_write:
            file.write(
                json.dumps(
                    sample,
                    ensure_ascii=False,
                )
                + "\n"
            )


