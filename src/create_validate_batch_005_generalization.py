def build_samples() -> list[dict]:
    samples = []
    sample_number = 1

    for card in cards:
        for sample_type, question, answer in card["qas"]:
            sample_id = f"gen_{sample_number:03d}"

            samples.append(
                {
                    "messages": [
                        {
                            "role": "system",
                            "content": SYSTEM_PROMPT,
                        },
                        {
                            "role": "user",
                            "content": (
                                f"متن منبع:\n{card['context']}\n\n"
                                f"سؤال:\n{question}"
                            ),
                        },
                        {
                            "role": "assistant",
                            "content": answer,
                        },
                    ],
                    "metadata": {
                        "id": sample_id,
                        "topic": "polymer_science",
                        "subtopic": card["subtopic"],
                        "type": sample_type,
                        "difficulty": "intermediate",
                        "language": "fa",
                        "verified": True,
                        "source": {
                            **card["source"],
                            "printed_pages": card["pages"],
                        },
                    },
                }
            )

            sample_number += 1

    return samples


def validate(samples: list[dict]) -> None:
    errors = []

    if len(cards) != 15:
        errors.append(
            f"تعداد کارت‌های مفهومی باید ۱۵ باشد، اما {len(cards)} است."
        )

    if len(samples) != 30:
        errors.append(
            f"تعداد نمونه‌ها باید ۳۰ باشد، اما {len(samples)} است."
        )

    expected_ids = {
        f"gen_{number:03d}"
        for number in range(1, 31)
    }

    actual_ids = []
    questions = []

    for sample in samples:
        metadata = sample.get("metadata", {})
        messages = sample.get("messages")
        sample_id = metadata.get("id")

        actual_ids.append(sample_id)

        if not isinstance(messages, list) or len(messages) != 3:
            errors.append(
                f"{sample_id}: messages باید دقیقاً ۳ پیام داشته باشد."
            )
            continue

        roles = [
            message.get("role")
            for message in messages
        ]

        if roles != ["system", "user", "assistant"]:
            errors.append(
                f"{sample_id}: ترتیب نقش‌ها نادرست است."
            )

        if metadata.get("verified") is not True:
            errors.append(
                f"{sample_id}: verified باید True باشد."
            )

        if metadata.get("language") != "fa":
            errors.append(
                f"{sample_id}: language باید fa باشد."
            )

        pages = metadata.get(
            "source",
            {},
        ).get("printed_pages")

        if (
            not isinstance(pages, list)
            or not pages
            or not all(
                isinstance(page, int) and page > 0
                for page in pages
            )
        ):
            errors.append(
                f"{sample_id}: printed_pages نامعتبر است."
            )

        user_text = messages[1].get("content", "")
        assistant_text = messages[2].get("content", "")

        if "سؤال:\n" not in user_text:
            errors.append(
                f"{sample_id}: قالب سؤال نامعتبر است."
            )
        else:
            questions.append(
                user_text.split("سؤال:\n", 1)[1].strip()
            )

        if not assistant_text.strip():
            errors.append(
                f"{sample_id}: پاسخ خالی است."
            )

    if set(actual_ids) != expected_ids:
        errors.append(
            "شناسه‌ها با gen_001 تا gen_030 مطابقت ندارند."
        )

    if len(actual_ids) != len(set(actual_ids)):
        errors.append("شناسه تکراری وجود دارد.")

    if len(questions) != len(set(questions)):
        errors.append("سؤال تکراری وجود دارد.")

    all_answers = " ".join(
        sample["messages"][2]["content"]
        for sample in samples
    )

    required_terms = [
        "Rp",
        "Xn",
        "C = ktr/kp",
        "ترموپلاستیک",
        "ترموست",
        "Tg",
        "Tm",
        "Đ",
        "Mn",
        "Mw",
        "[η]",
        "میسل",
        "کاتیونی",
        "آنیونی",
        "χ",
        "E(t)",
        "J(t)",
    ]

    for term in required_terms:
        if term not in all_answers:
            errors.append(
                f"اصطلاح لازم در پاسخ‌ها وجود ندارد: {term}"
            )

    if errors:
        print("اعتبارسنجی ناموفق بود:")

        for error in errors:
            print("-", error)

        raise SystemExit(1)


def main() -> None:
    samples = build_samples()
    validate(samples)

    OUTPUT_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with OUTPUT_PATH.open(
        "w",
        encoding="utf-8",
    ) as file:
        for sample in samples:
            file.write(
                json.dumps(
                    sample,
                    ensure_ascii=False,
                )
                + "\n"
            )

    print("=" * 72)
    print("فایل ساخته شد:", OUTPUT_PATH)
    print("تعداد نمونه‌ها:", len(samples))
    print("تعداد مفاهیم پایه:", len(cards))
    print(
        "تعداد شناسه‌های یکتا:",
        len({
            sample["metadata"]["id"]
            for sample in samples
        }),
    )

    type_counts = Counter(
        sample["metadata"]["type"]
        for sample in samples
    )

    print("\nتوزیع نوع نمونه‌ها:")

    for sample_type, count in sorted(type_counts.items()):
        print(f"- {sample_type}: {count}")

    print("\nنتیجه اعتبارسنجی:")
    print("همه ۳۰ نمونه معتبر هستند.")
    print("هر مفهوم با دو صورت سؤال متفاوت پوشش داده شده است.")
    print("شناسه یا سؤال تکراری وجود ندارد.")


